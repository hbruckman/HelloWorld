const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const output = path.resolve(__dirname, '../../artifacts');
fs.mkdirSync(output, { recursive: true });
(async () => {
 const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || undefined,headless:true,args:['--no-sandbox']});
 const page = await browser.newPage({viewport:{width:1440,height:1160}, deviceScaleFactor:1});
 const errors=[];page.on('pageerror', e=>errors.push(e.message));
 await page.goto(process.env.ATLAS_BASE_URL || 'http://127.0.0.1:5080');
 await page.evaluate(() => document.fonts.ready);
 await page.screenshot({path:path.join(output, 'atlas-desktop.png'),fullPage:true});
 await page.locator('#archiveNav').click();
 await page.getByText('No expeditions yet.', {exact:false}).waitFor();
 await page.locator('#aboutNav').click();await page.getByText('C# at the core.').waitFor();
 await page.locator('#overviewNav').click();
 await page.locator('#scenario').selectOption('europa');
 await page.locator('#probes').fill('8');
 await page.locator('#launch').click();
 await page.waitForFunction(()=>document.querySelectorAll('.probe').length===8);
 assert.equal(await page.locator('#scenario').isDisabled(),true);
 await page.waitForFunction(()=>Number(document.getElementById('progressValue').textContent.replace('%','')) >= 20);
 await page.screenshot({path:path.join(output, 'atlas-active.png'),fullPage:true});
 await page.waitForFunction(()=>document.getElementById('progressValue').textContent==='100%',null,{timeout:40000});
 assert.equal(await page.locator('#coverage').innerText(),'98.4%');
 assert.equal(await page.locator('.event').count(),7);
 assert.equal(await page.locator('#launch').isEnabled(),true);
 const downloadPromise=page.waitForEvent('download');await page.locator('#export').click();
 const download=await downloadPromise;await download.saveAs(path.join(output, 'atlas-report.json'));
 const report=JSON.parse(require('node:fs').readFileSync(path.join(output, 'atlas-report.json'),'utf8'));
 assert.equal(report.status,'Complete');assert.equal(report.probes,8);assert.equal(report.samples,4080);assert.equal(report.simulated,true);
 await page.locator('#archiveNav').click();assert.equal(await page.locator('.archive-card').count(),1);
 await page.locator('.archive-card').click();await page.locator('#overview').waitFor({state:'visible'});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth),true);
 await page.screenshot({path:path.join(output, 'atlas-mobile.png'),fullPage:true});
 await page.locator('#scenario').selectOption('orion');await page.locator('#launch').click();
 await page.waitForFunction(()=>document.getElementById('archiveCount').textContent==='02');
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('PASS: desktop, mobile, navigation, launch, live telemetry, completion, JSON export, archive, second launch; no browser errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
